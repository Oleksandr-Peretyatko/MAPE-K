package org.anonymous.msrefactor.rt.analyze;

import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonProperty;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/**
 * A single candidate refactoring operation identified by the Analyze phase.
 *
 * <p>Candidates are generated from detected hotspots and ranked against a
 * prioritised quality attribute list by {@code SimpleRankingStrategy}.
 * Final selection and execution planning are deferred to the Plan phase.
 */
@Data
@Builder(toBuilder = true)
@NoArgsConstructor
@AllArgsConstructor
@JsonInclude(JsonInclude.Include.NON_NULL)
@com.fasterxml.jackson.annotation.JsonIgnoreProperties(ignoreUnknown = true)
public class CandidateOperation {

    /** The refactoring operation type. */
    private OperationType operation;

    /** Primary target service or aggregate (e.g., "execution-service"). May be null for system-wide ops. */
    private String targetService;

    /** Secondary target (e.g., the destination service for MoveEntity). Null when not applicable. */
    private String secondaryTarget;

    /**
     * Short one-line description of what this operation does: entity, source, destination.
     * Intended as a card headline (e.g. "Move Answer from tournament → quiz").
     */
    @JsonInclude(JsonInclude.Include.NON_NULL)
    private String summary;

    /** Human-readable explanation of why this operation is applicable to the current snapshot. */
    private String whyApplicable;

    /** The quality attribute this operation primarily improves. */
    private QualityAttribute primaryQaTarget;

    /**
     * Secondary quality effects: attribute → description of the effect (positive or negative).
     * For example: {CONSISTENCY: "May introduce replica lag risk"}.
     */
    private Map<QualityAttribute, String> secondaryQaEffects;

    /** Structural or runtime preconditions that must hold before this operation can be applied. */
    private List<String> preconditions;

    /** Known risks or trade-offs of applying this operation. */
    private List<String> risks;

    /** Other operations that should be applied before or alongside this one. */
    private List<String> dependencies;

    /**
     * Entity class names directly involved in this operation.
     * For the replica operations: the entity being replicated or removed.
     * Null or empty for operation types where entities are not individually named.
     */
    private List<String> affectedEntities;

    /**
     * Concrete blueprint describing how this operation would be executed: before/after
     * aggregate views, entity moves, invariant changes, and implementation steps.
     * Null when no static structural data is available for the target service.
     */
    @JsonInclude(JsonInclude.Include.NON_NULL)
    private RefactorBlueprint blueprint;

    /**
     * When non-null this candidate is blocked by an architect constraint.
     * The value is the human-readable reason from the matching constraint rule.
     * Blocked candidates are returned after all unblocked ones so the UI can
     * show them in a separate "Blocked by constraints" section.
     */
    @JsonInclude(JsonInclude.Include.NON_NULL)
    private String blockedBy;

    /**
     * Advisory notes from non-blocking constraint rules (warning-level).
     * Shown as warning badges on the candidate card without affecting rank.
     */
    @JsonInclude(JsonInclude.Include.NON_NULL)
    private List<String> warnings;

    /**
     * Score of this operation for the primary QA (SIMPLE_RANK mode only).
     * Integer in [-2, +2]. Not set in LEGACY mode.
     */
    @JsonInclude(JsonInclude.Include.NON_DEFAULT)
    private int primaryQaScore;

    /**
     * Human-readable explanation of why this candidate has its current rank (SIMPLE_RANK mode only).
     * Shows service severity and per-QA scores. Not set in LEGACY mode.
     */
    @JsonInclude(JsonInclude.Include.NON_NULL)
    private String rankReason;

    // ─── Selection evidence (populated for SPLIT_AGGREGATE and CREATE_REPLICA) ──

    /**
     * Classification of how invariants in the source aggregate are affected.
     * Null when no invariant data is available or not applicable.
     */
    @JsonInclude(JsonInclude.Include.NON_NULL)
    private InvariantImpact invariantImpact;

    /**
     * Ranked alternatives that were considered but not selected.
     * Allows architects to understand why the selected candidate was preferred.
     */
    @JsonInclude(JsonInclude.Include.NON_NULL)
    private List<AlternativeCandidate> alternatives;

    /**
     * Ordered validation steps to run after applying this operation.
     * Null when not generated by a selector.
     */
    @JsonInclude(JsonInclude.Include.NON_NULL)
    private List<ValidationStep> validationPlan;

    /**
     * Composite score from the entity/partition selection algorithm (0.0 = not computed).
     * Independent of the Operation→QA matrix score used for ranking.
     */
    @JsonInclude(JsonInclude.Include.NON_DEFAULT)
    private double selectionScore;

    /** Composite risk score from invariant and dependency analysis (0.0 = not computed). */
    @JsonInclude(JsonInclude.Include.NON_DEFAULT)
    private double riskScore;

    /** Estimated implementation feasibility (0.0 = not computed, 1.0 = very feasible). */
    @JsonInclude(JsonInclude.Include.NON_DEFAULT)
    private double feasibilityScore;

    /**
     * Derived CLI command signature for this candidate (e.g., "/create-replica execution Course --to quiz").
     * Computed from the other fields — not stored, always reflects current state.
     */
    @JsonProperty("commandSignature")
    public String getCommandSignature() {
        if (operation == null) return null;
        String entity = affectedEntities != null && !affectedEntities.isEmpty()
                            ? affectedEntities.get(0) : "?";
        String sec = secondaryTarget != null ? secondaryTarget : "?";
        return switch (operation) {
            case MERGE_AGGREGATES   -> "/merge-aggregate %s %s".formatted(targetService, sec);
            case SPLIT_AGGREGATE    -> {
                // Prefer the full partition from the blueprint: real entity lists + invariant tags +
                // the invented satellite name in --new-aggregate (the grammar the execute skill expects).
                if (blueprint != null && blueprint.getAfter() != null && blueprint.getAfter().size() == 2) {
                    AggregateSnapshot coreAggr = blueprint.getAfter().get(0);
                    AggregateSnapshot satAggr  = blueprint.getAfter().get(1);
                    String coreList = (coreAggr.getEntities() != null && !coreAggr.getEntities().isEmpty())
                            ? String.join(",", coreAggr.getEntities()) : "?";
                    String satList = (satAggr.getEntities() != null && !satAggr.getEntities().isEmpty())
                            ? String.join(",", satAggr.getEntities()) : "?";
                    StringBuilder cmd = new StringBuilder("/split-aggregate ")
                            .append(targetService)
                            .append(" --core ").append(coreList)
                            .append(" --satellite ").append(satList);
                    String invPartition = buildInvariantPartition(coreAggr, satAggr);
                    if (!invPartition.isEmpty()) cmd.append(" --invariants ").append(invPartition);
                    if (satAggr.getAggregateName() != null && !satAggr.getAggregateName().isBlank())
                        cmd.append(" --new-aggregate ").append(satAggr.getAggregateName());
                    yield cmd.toString();
                }
                // Fallback: legacy single-token form derived from affectedEntities.
                String core = (affectedEntities != null && affectedEntities.size() > 0) ? affectedEntities.get(0) : "?";
                String sat  = (affectedEntities != null && affectedEntities.size() > 1) ? affectedEntities.get(1) : "?";
                yield "/split-aggregate %s --core %s --satellite %s".formatted(targetService, core, sat);
            }
            // One source, one entity, one target — CreateReplica has no list-valued argument, so
            // only element 0 is ever read.
            case CREATE_REPLICA     -> "/create-replica %s %s --to %s".formatted(sec, entity, targetService);
            case REMOVE_REPLICA     -> "/remove-replica %s %s --source %s".formatted(targetService, entity, sec);
        };
    }

    /**
     * Builds the {@code --invariants} partition string for a split from the two after-aggregate
     * snapshots: {@code inv@core} for the core aggregate's invariants and {@code inv@satellite} for the
     * satellite's. Returns "" when neither side lists invariants (the execute skill then auto-assigns).
     */
    private static String buildInvariantPartition(AggregateSnapshot core, AggregateSnapshot satellite) {
        List<String> parts = new ArrayList<>();
        if (core != null && core.getInvariants() != null)
            for (String i : core.getInvariants()) parts.add(i + "@core");
        if (satellite != null && satellite.getInvariants() != null)
            for (String i : satellite.getInvariants()) parts.add(i + "@satellite");
        return String.join(",", parts);
    }
}
